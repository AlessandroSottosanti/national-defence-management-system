package it.application.nationaldefencemanagementsystem.Entities;

public enum EquipmentCondition {
    NEW,          // Brand new, never used
    EXCELLENT,    // Mint condition, minimal use
    GOOD,         // Standard operational wear, fully functional
    WORN,         // Noticeable wear, might need maintenance soon
    DAMAGED,      // Structural or functional issues, needs repair
    UNSERVICEABLE // Beyond economical repair, destroyed
}